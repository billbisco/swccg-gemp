/**
 * Set: Virtual Set 15: Galactic Frontier
 * Type: Effect
 * Subtype: Starting
 * Title: Anger, Fear, Aggression (V)
 */
public class Card1115_001 extends AbstractStartingEffect {
    public Card1115_001() {
        super(Side.LIGHT, 4, Title.Anger_Fear_Aggression, ExpansionSet.VIRTUAL_ORIGINAL_SET_15, Rarity.V);
        setVirtualSuffix(true);
        setLore("'The dark side of the Force are they. Easily they flow, quick to join you in a fight.'");
        setGameText("Deploy on table with 12 cards from outside your deck face-down under here. Thrice per game, may play a Defensive Shield or deploy (at any time) [Virtual Set 9] The Professor from here (as if from hand). Players do not draw or activate using Drop!. Unless [Virtual Set 15] Knowledge And Defense on table, each time a player attempts to deploy or take a card for free (except their first time per game) they must first use 1 Force.");
        addIcons(Icon.DAGOBAH);
        
    }

    @Override
    protected List<Modifier> getGameTextWhileActiveInPlayModifiers(SwccgGame game, final PhysicalCard self) {
        String playerId = self.getOwner();

        List<Modifier> modifiers = new LinkedList<Modifier>();
        return modifiers;
    }

    @Override
    protected List<RequiredGameTextTriggerAction> getGameTextRequiredAfterTriggers(final SwccgGame game, EffectResult effectResult, final PhysicalCard self, int gameTextSourceCardId) {
        String playerId = self.getOwner();

        // Check condition(s)
        if (TriggerConditions.justDeployed(game, effectResult, self)) {

            RequiredGameTextTriggerAction action = new RequiredGameTextTriggerAction(self, gameTextSourceCardId);
            action.skipInitialMessageAndAnimation();
            // Perform result(s)
            action.appendEffect(
                    new StackCardsFromOutsideDeckEffect(action, playerId, 12, 12, self, Filters.any));
            return Collections.singletonList(action);
        }
        return null;
    }

    @Override
    protected List<TopLevelGameTextAction> getGameTextTopLevelActions(final String playerId, SwccgGame game, final PhysicalCard self, int gameTextSourceCardId) {
        GameTextActionId gameTextActionId = GameTextActionId.ANGER_FEAR_AGGRESSION__PLAY_CARD;
        Filter filter = Filters.or(Filters.Defensive_Shield, Filters.and(Filters.title("The Professor"), new Filter() {
            @Override
            public boolean accepts(com.gempukku.swccgo.game.state.GameState gameState, com.gempukku.swccgo.logic.modifiers.querying.ModifiersQuerying modifiersQuerying, PhysicalCard physicalCard) {
                return physicalCard.getBlueprint().getExpansionSet() == ExpansionSet.VIRTUAL_ORIGINAL_SET_9;
            }
        }));

        if (GameConditions.isThreeTimesPerGame(game, self, gameTextActionId)
                && GameConditions.hasStackedCards(game, self, filter)) {

            final TopLevelGameTextAction action = new TopLevelGameTextAction(self, gameTextSourceCardId, gameTextActionId);
            action.setText("Play a Defensive Shield or The Professor");
            action.appendUsage(
                    new ThreeTimesPerGameEffect(action));
            // Choose target(s)
            action.appendTargeting(
                    new ChooseStackedCardEffect(action, playerId, self, filter) {
                        @Override
                        protected void cardSelected(PhysicalCard selectedCard) {
                            // Perform result(s)
                            action.appendEffect(
                                    new PlayStackedCardEffect(action, self, selectedCard));
                        }
                    }
            );
            return Collections.singletonList(action);
        }
        return null;
    }
}
